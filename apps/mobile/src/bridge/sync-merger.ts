export interface TimestampedSyncRecord<TPayload = Record<string, unknown>> {
  id: string;
  updatedAt: number;
  payload: TPayload;
}

export interface CompanionPairingCredentials {
  baseUrl: string;
  pairingToken: string;
  hostname?: string;
}

/**
 * Conflict-safe last-write-wins merge keyed by `id` and `updatedAt` timestamp.
 * Guarantees neither Desktop nor Android loses newer mastery scores, lessons, or pitfall memos.
 */
export function mergeRecordsByTimestamp<TPayload>(
  localRecords: TimestampedSyncRecord<TPayload>[],
  remoteRecords: TimestampedSyncRecord<TPayload>[]
): TimestampedSyncRecord<TPayload>[] {
  const merged = new Map<string, TimestampedSyncRecord<TPayload>>();

  for (const rec of localRecords) {
    merged.set(rec.id, rec);
  }

  for (const remote of remoteRecords) {
    const existing = merged.get(remote.id);
    if (!existing || remote.updatedAt >= existing.updatedAt) {
      merged.set(remote.id, remote);
    }
  }

  return Array.from(merged.values()).sort((a, b) => b.updatedAt - a.updatedAt);
}

/**
 * Parses QR code JSON payloads or `yourtutor://pair?url=...&token=...` deep links
 * generated by the Desktop Companion Bridge settings screen.
 */
export function parseCompanionPairingPayload(raw: string): CompanionPairingCredentials | null {
  const trimmed = raw.trim();
  if (!trimmed) {
    return null;
  }

  if (trimmed.startsWith('{')) {
    try {
      const parsed = JSON.parse(trimmed) as {
        baseUrl?: unknown;
        token?: unknown;
        hostname?: unknown;
      };
      if (typeof parsed.baseUrl === 'string' && typeof parsed.token === 'string') {
        return {
          baseUrl: parsed.baseUrl.replace(/\/+$/, ''),
          pairingToken: parsed.token.trim(),
          hostname: typeof parsed.hostname === 'string' ? parsed.hostname : undefined,
        };
      }
    } catch {
      return null;
    }
  }

  if (trimmed.startsWith('yourtutor://pair')) {
    try {
      const parsedUrl = new URL(trimmed);
      const baseUrl = parsedUrl.searchParams.get('url');
      const token = parsedUrl.searchParams.get('token');
      const hostname = parsedUrl.searchParams.get('host') ?? undefined;
      if (baseUrl && token) {
        return {
          baseUrl: baseUrl.replace(/\/+$/, ''),
          pairingToken: token.trim(),
          hostname,
        };
      }
    } catch {
      return null;
    }
  }

  return null;
}
